#!/usr/bin/env python3
# Writes stubs_com.c: a logging stub vtable for every COM interface the
# D3D11 device and its units call, from mingw-w64's headers. Each method
# logs its name and arguments (log_word/log_bytes in stubs.c): an object
# by its id, a struct behind a const pointer by its bytes, an array by
# the count before it. A method stubs.c defines as hook_<family>_<name>
# is handed to it instead. Usage: gen_stubs.py <include dir> <stubs.c> <out>
import re, sys
inc, hooks_src, out = sys.argv[1], sys.argv[2], sys.argv[3]

# interface, header, family (the prefix of its hooks)
IFACES = [
    ('ID3D11Device1', 'd3d11_1.h', 'dev'),
    ('ID3D11DeviceContext1', 'd3d11_1.h', 'ctx'),
    ('IDXGIDevice', 'dxgi.h', 'dxgidev'),
    ('IDXGIAdapter1', 'dxgi.h', 'adapter'),
    ('ID3D10Blob', 'd3dcommon.h', 'blob'),
    ('ID3D11Buffer', 'd3d11.h', 'res'),
    ('ID3D11Texture2D', 'd3d11.h', 'res'),
    ('ID3D11ShaderResourceView', 'd3d11.h', 'view'),
    ('ID3D11RenderTargetView', 'd3d11.h', 'view'),
    ('ID3D11DepthStencilView', 'd3d11.h', 'view'),
    ('ID3D11UnorderedAccessView', 'd3d11.h', 'view'),
    ('ID3D11VertexShader', 'd3d11.h', 'child'),
    ('ID3D11PixelShader', 'd3d11.h', 'child'),
    ('ID3D11InputLayout', 'd3d11.h', 'child'),
    ('ID3D11BlendState', 'd3d11.h', 'child'),
    ('ID3D11DepthStencilState', 'd3d11.h', 'child'),
    ('ID3D11RasterizerState', 'd3d11.h', 'child'),
    ('ID3D11SamplerState', 'd3d11.h', 'child'),
]
KIND = {name: i for i, (name, _, _) in enumerate(IFACES)}
hooks = set(re.findall(r'\bhook_(\w+)\s*\(', open(hooks_src).read()))

def vtbl(name, header):
    src = open('%s/%s' % (inc, header)).read()
    m = re.search(r'typedef struct %sVtbl \{(.*?)\} %sVtbl;' % (name, name), src, re.S)
    meths = []
    for mm in re.finditer(r'(\w[\w \*]*?)\s*\(STDMETHODCALLTYPE \*(\w+)\)\(\s*(.*?)\);', m.group(1), re.S):
        args = [a.strip() for a in mm.group(3).replace('\n', ' ').split(',')]
        params = []
        for a in args[1:]:
            a = re.sub(r'\s+', ' ', a)
            arr = re.match(r'(.*?)(\w+)\[(\d+)\]$', a)
            if arr:
                params.append((arr.group(1).strip() + ' *', arr.group(2), int(arr.group(3))))
                continue
            p = re.match(r'(.*?)(\w+)$', a)
            params.append((p.group(1).strip(), p.group(2), 0))
        meths.append((mm.group(1).strip(), mm.group(2), params, args[0]))
    return meths

def is_iface(t):
    b = t.replace('const', '').replace('*', '').strip()
    return re.match(r'^(ID3D1[01]\w*|IDXGI\w*|IUnknown)$', b) is not None

def base(t):
    return t.replace('const', '').replace('*', '').strip()

SCALAR_FLOAT = ('FLOAT',)
lines = ['/* Generated by gen_stubs.py from mingw-w64\'s headers: do not edit. */',
         '#define COBJMACROS', '#define CINTERFACE', '#include <d3d11_1.h>', '#include <dxgi.h>',
         '#include "stubs.h"', '']
inits = []
protos = set()
for name, header, fam in IFACES:
    for ret, meth, params, this in vtbl(name, header):
        fn = 's_%s_%s' % (name, meth)
        plist = ', '.join([this] +
                          [('%s %s[%d]' % (t[:-2].strip(), n, c)) if c else '%s %s' % (t, n) for t, n, c in params])
        hk = '%s_%s' % (fam, meth)
        if meth in ('QueryInterface', 'AddRef', 'Release'):
            hk = 'obj_%s' % meth
        if hk in hooks and hk not in protos:
            protos.add(hk)
            lines.append('%s hook_%s(%s);' % (ret, hk, ', '.join(['stub_obj* o'] + [
                ('%s %s[%d]' % (t[:-2].strip(), n, c)) if c else '%s %s' % (t, n) for t, n, c in params])))
        lines.append('static %s STDMETHODCALLTYPE %s(%s)' % (ret, fn, plist))
        lines.append('{')
        if hk in hooks:
            call = 'hook_%s(%s)' % (hk, ', '.join(['(stub_obj*)This'] + [n for t, n, c in params]))
            lines.append('\t%s%s;' % ('' if ret == 'void' else 'return ', call))
            lines.append('}')
            inits.append((name, meth, fn))
            continue
        lines.append('\tstub_call((stub_obj*)This, "%s::%s");' % (name, meth))
        count = None
        for i, (t, n, c) in enumerate(params):
            if re.match(r'^Num\w+$', n) or n in ('NumViews', 'NumBuffers'):
                count = n
            if c:
                if base(t) in SCALAR_FLOAT:
                    lines.append('\tlog_bytes(%s, %d * sizeof(FLOAT));' % (n, c))
                else:
                    lines.append('\tlog_bytes(%s, %d * sizeof(%s));' % (n, c, base(t)))
            elif '**' in t.replace(' ', '') or '*const*' in t.replace(' ', ''):
                b = base(t)
                if 'const' in t.split('*')[-2] or t.replace(' ', '').endswith('*const*'):
                    # an array of objects in
                    lines.append('\tstub_log_objs((void* const*)%s, %s);' % (n, count or '1'))
                elif is_iface(t) and b in KIND:
                    lines.append('\tif (%s) *%s = (%s*)stub_new(%d);' % (n, n, b, KIND[b]))
                    lines.append('\tif (%s) log_word(stub_id(*%s));' % (n, n))
                elif is_iface(t) or b == 'void':
                    lines.append('\tif (%s) *%s = NULL;' % (n, n))
            elif t in ('REFIID', 'REFGUID'):
                lines.append('\tlog_bytes(%s, sizeof(GUID));' % n)
            elif '*' in t and base(t) == 'void' and t.startswith('const') and i + 1 < len(params) \
                    and params[i + 1][0] == 'SIZE_T':
                lines.append('\tlog_bytes(%s, %s);' % (n, params[i + 1][1]))
            elif '*' in t:
                b = base(t)
                if is_iface(t):
                    lines.append('\tlog_word(stub_id(%s));' % n)
                elif t.startswith('const') and b not in ('void', 'char', 'WCHAR'):
                    cnt = count
                    if cnt:
                        lines.append('\tif (%s) log_bytes(%s, sizeof(%s) * (size_t)%s); else log_word(0);' % (n, n, b, cnt))
                    else:
                        lines.append('\tif (%s) log_bytes(%s, sizeof(%s)); else log_word(0);' % (n, n, b))
                elif t.startswith('const') and b in ('char',):
                    lines.append('\tif (%s) log_string(%s); else log_word(0);' % (n, n))
                else:
                    lines.append('\tlog_word(%s != NULL);' % n)
            elif base(t) in SCALAR_FLOAT:
                lines.append('\tlog_float(%s);' % n)
            else:
                lines.append('\tlog_word((u64)(%s));' % n)
        if ret == 'HRESULT':
            lines.append('\treturn S_OK;')
        elif ret != 'void':
            lines.append('\treturn (%s)0;' % ret)
        lines.append('}')
        inits.append((name, meth, fn))
    lines.append('')

for name, header, fam in IFACES:
    lines.append('static %sVtbl s_vt_%s;' % (name, name))
lines.append('')
lines.append('const void* stub_vtbl(unsigned kind)')
lines.append('{')
lines.append('\tstatic int done;')
lines.append('\tif (!done)')
lines.append('\t{')
lines.append('\t\tdone = 1;')
for name, meth, fn in inits:
    lines.append('\t\ts_vt_%s.%s = %s;' % (name, meth, fn))
lines.append('\t}')
lines.append('\tswitch (kind)')
lines.append('\t{')
for name, header, fam in IFACES:
    lines.append('\t\tcase %d: return &s_vt_%s;' % (KIND[name], name))
lines.append('\t}')
lines.append('\treturn NULL;')
lines.append('}')
open(out, 'w').write('\n'.join(lines) + '\n')
