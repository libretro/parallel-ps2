#!/usr/bin/env python3
# Writes scenario.h: every GSBlock call with literal
# arguments, as the C++ templates need them. Run from this directory.
masks = ['0xffffffffu', '0x00ffffffu', '0xff000000u', '0x0000ffffu', '0xffff0000u', '0x0f0f0f0fu', '0u', '0x00ff00ffu']
L = []
L.append('''/* Every GSBlock call: reads and writes of a column (0-3 and by row) or a
 * block, sources aligned and not, the 32-bit write's masks; expanding to
 * 32 and 16 bits (TEXA and AEM over zero colours, palettes) and unpacking
 * 24-bit and high 8/4-bit pixels at odd pitches. Over random blocks, rows
 * and palettes; the hash takes the blocks and rows after each. Through
 * the C block swizzle (gs_block.h, main.c) and the C++ GSBlock (the
 * oracle), which define the call macros: GENERATED by gen.py. */

static void sc_writes(void)
{''')
for al in (0, 32):
    for i in range(4):
        for m in masks:
            L.append('\tsc_fill(); W32(%d, %d, %s, sc_block, sc_src(%d), SC_PITCH); sc_hash_block();' % (i, al, m, al))
        L.append('\tsc_fill(); W16(%d, %d, sc_block, sc_src(%d), SC_PITCH); sc_hash_block();' % (i, al, al))
        L.append('\tsc_fill(); W8(%d, %d, sc_block, sc_src(%d), SC_PITCH); sc_hash_block();' % (i, al, al))
        L.append('\tsc_fill(); W4(%d, %d, sc_block, sc_src(%d), SC_PITCH); sc_hash_block();' % (i, al, al))
    for y in (0, 1, 2, 3, 5, 6, 7, 9, 12, 14, 15):
        L.append('\tsc_fill(); W32Y(%d, %d, 0xffffffffu, sc_block, sc_src(%d), SC_PITCH); sc_hash_block();' % (y, al, al))
        L.append('\tsc_fill(); W16Y(%d, %d, sc_block, sc_src(%d), SC_PITCH); sc_hash_block();' % (y, al, al))
        L.append('\tsc_fill(); W8Y(%d, %d, sc_block, sc_src(%d), SC_PITCH); sc_hash_block();' % (y, al, al))
        L.append('\tsc_fill(); W4Y(%d, %d, sc_block, sc_src(%d), SC_PITCH); sc_hash_block();' % (y, al, al))
    for m in masks[:3]:
        L.append('\tsc_fill(); WB32(%d, %s, sc_block, sc_src(%d), SC_PITCH); sc_hash_block();' % (al, m, al))
    L.append('\tsc_fill(); WB16(%d, sc_block, sc_src(%d), SC_PITCH); sc_hash_block();' % (al, al))
    L.append('\tsc_fill(); WB8(%d, sc_block, sc_src(%d), SC_PITCH); sc_hash_block();' % (al, al))
    L.append('\tsc_fill(); WB4(%d, sc_block, sc_src(%d), SC_PITCH); sc_hash_block();' % (al, al))
L.append('}\n\nstatic void sc_reads(void)\n{')
for i in range(4):
    for f in ('R32', 'R16', 'R8', 'R4'):
        L.append('\tsc_fill(); %s(%d, sc_block, sc_rows, SC_PITCH); sc_hash_rows();' % (f, i))
for y in (0, 1, 2, 3, 5, 6, 7, 9, 12, 14, 15):
    for f in ('R32Y', 'R16Y', 'R8Y', 'R4Y'):
        L.append('\tsc_fill(); %s(%d, sc_block, sc_rows, SC_PITCH); sc_hash_rows();' % (f, y))
for f in ('RB32', 'RB16', 'RB8', 'RB4', 'RB4P', 'RB8HP', 'RB4HLP', 'RB4HHP'):
    L.append('\tsc_fill(); %s(sc_block, sc_rows, SC_PITCH); sc_hash_rows();' % f)
L.append('}\n')

L.append('static void sc_expands(void)\n{')
texa = [(0x80, 0x00), (0x00, 0xff), (0x5a, 0xa5)]
for aem in (0, 1):
    for t0, t1 in texa:
        L.append('\tsc_fill(); sc_zeros(); EB24(%d, sc_block, sc_rows, SC_PITCH, 0x%02x); sc_hash_rows();' % (aem, t0))
        L.append('\tsc_fill(); sc_zeros(); EB16(%d, sc_block, sc_rows, SC_PITCH, 0x%02x, 0x%02x); sc_hash_rows();' % (aem, t0, t1))
        L.append('\tsc_fill(); sc_zeros(); RE24(%d, sc_block, sc_rows, SC_PITCH, 0x%02x); sc_hash_rows();' % (aem, t0))
        L.append('\tsc_fill(); sc_zeros(); RE16(%d, sc_block, sc_rows, SC_PITCH, 0x%02x, 0x%02x); sc_hash_rows();' % (aem, t0, t1))
L.append('}\n\nstatic void sc_palettes(void)\n{\n\tint n;\n\tfor (n = 0; n < 3; n++)\n\t{')
for f in ('EB8_32', 'EB8_16', 'RE8_32', 'RE8_32HSW', 'RE4_32', 'RE8H_32', 'RE8H_32HSW', 'RE4HL_32', 'RE4HH_32',
          'EB8H_32', 'EB8H_16', 'EB4HL_32', 'EB4HL_16', 'EB4HH_32', 'EB4HH_16'):
    L.append('\t\tsc_fill(); %s(sc_block, sc_rows, SC_PITCH, sc_pal32); sc_hash_rows();' % f)
for f in ('EB4_32', 'EB4_16'):
    L.append('\t\tsc_fill(); %s(sc_block, sc_rows, SC_PITCH, sc_pal64); sc_hash_rows();' % f)
L.append('\t}')
L.append('}\n\nstatic void sc_unpacks(void)\n{')
for off in (0, 4, 3, 1):
    for p in ('SC_PITCH', 'SC_PITCH - 8', '28'):
        for f in ('UW24', 'UW8H', 'UW4HL', 'UW4HH'):
            if f == 'UW24' and p == '28':
                continue
            L.append('\tsc_fill(); %s(sc_src_base + %d, %s, sc_block); sc_hash_block();' % (f, off, p))
L.append('}\n')
open('scenario.h', 'w').write('\n'.join(L))
