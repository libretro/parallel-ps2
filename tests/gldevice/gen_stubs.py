#!/usr/bin/env python3
# Writes stubs_gl.c: a logging stub for every GL entry point the OpenGL
# device and the GL units it links call (named in syms.txt), from glad.h's
# prototypes. Each logs its name and arguments (log_word/log_bytes in
# stubs.c), and the data behind a pointer where its size is known.
import re, sys
glad, syms, out = sys.argv[1], sys.argv[2], sys.argv[3]
src = open(glad).read()
names = [l.strip() for l in open(syms) if l.startswith('glad_gl')]
flags = [l.strip() for l in open(syms) if l.startswith('GLAD_GL')]
tdefs = {}
for m in re.finditer(r'typedef (.+?) \(APIENTRYP (PFNGL\w+PROC)\)\((.*?)\);', src):
    tdefs[m.group(2)] = (m.group(1).strip(), m.group(3).strip())
decl = {}
for m in re.finditer(r'GLAPI (PFNGL\w+PROC) (glad_gl\w+);', src):
    decl[m.group(2)] = m.group(1)

def split_args(a):
    if a in ('', 'void'): return []
    res = []
    for p in a.split(','):
        p = p.strip()
        m = re.match(r'(.*?)(\w+)$', p)
        res.append((m.group(1).strip(), m.group(2)))
    return res

UNIFORM_N = {'1': 1, '2': 2, '3': 3, '4': 4}
lines = ['/* Generated by gen_stubs.py from glad.h: do not edit. */',
         '#include "glad.h"', '#include "stubs.h"', '']
for g in names:
    fn = g[len('glad_'):]
    pfn = decl[g]
    ret, args = tdefs[pfn]
    al = split_args(args)
    body = ['\tlog_name("%s");' % fn]
    special = None
    # pointers whose data is logged, by the function
    for i, (t, n) in enumerate(al):
        if '*' in t or t in ('GLDEBUGPROC', 'GLDEBUGPROCKHR', 'GLDEBUGPROCARB'):
            continue
        if t in ('GLfloat', 'GLclampf'):
            body.append('\tlog_float(%s);' % n)
        elif t in ('GLdouble', 'GLclampd'):
            body.append('\tlog_double(%s);' % n)
        elif t == 'GLsync':
            body.append('\tlog_word(stub_sync_id(%s));' % n)
        else:
            body.append('\tlog_word((u64)(%s));' % n)
    ptrs = [(t, n) for (t, n) in al if '*' in t]
    m = re.match(r'gl(Gen|Create)(\w+)s$', fn)
    if m and len(ptrs) == 1 and 'GLuint' in ptrs[0][0] and fn not in ('glCreateShader', 'glCreateProgram'):
        cnt = [n for (t, n) in al if t == 'GLsizei'][0]
        body.append('\tstub_gen(%s, %s);' % (cnt, ptrs[0][1]))
    elif re.match(r'glDelete\w+s$', fn) and len(ptrs) == 1:
        cnt = [n for (t, n) in al if t == 'GLsizei'][0]
        body.append('\tlog_bytes(%s, sizeof(GLuint) * (size_t)%s);' % (ptrs[0][1], cnt))
    elif re.match(r'glUniform(\d)(f|i|ui)v$', fn):
        mm = re.match(r'glUniform(\d)(f|i|ui)v$', fn)
        body.append('\tlog_bytes(value, 4u * %s * (size_t)count);' % mm.group(1))
    elif re.match(r'glClearBuffer(f|i|ui)v$', fn):
        body.append('\tlog_bytes(value, 4u * (buffer == GL_COLOR ? 4u : 1u));')
    elif fn in ('glBufferData', 'glBufferSubData'):
        body.append('\tif (data) log_bytes(data, (size_t)size);')
    elif fn == 'glShaderSource':
        body.append('\tstub_shader_source(count, string, length);')
    elif fn in ('glDrawBuffers',):
        body.append('\tlog_bytes(bufs, sizeof(GLenum) * (size_t)n);')
    elif fn == 'glInvalidateFramebuffer':
        body.append('\tlog_bytes(attachments, sizeof(GLenum) * (size_t)numAttachments);')
    elif fn in ('glDebugMessageControl', 'glDebugMessageControlKHR'):
        body.append('\tif (ids) log_bytes(ids, sizeof(GLuint) * (size_t)count);')
    elif fn in ('glDrawElementsBaseVertex', 'glDrawElements', 'glDrawElementsBaseVertexOES', 'glDrawElementsBaseVertexEXT'):
        body.append('\tlog_word((u64)(uintptr_t)indices);')
    elif fn in ('glVertexAttribPointer', 'glVertexAttribIPointer'):
        body.append('\tlog_word((u64)(uintptr_t)pointer);')
    elif fn == 'glGetUniformLocation':
        body.append('\tlog_string(name);')
    else:
        for (t, n) in ptrs:
            body.append('\tlog_word(%s != 0);' % n)
    # answers
    if fn == 'glGetIntegerv':
        body.append('\tstub_get_integerv(pname, data);')
    elif fn in ('glGetShaderiv', 'glGetProgramiv'):
        body.append('\t*params = stub_get_object_iv(pname);')
    elif fn in ('glGetShaderInfoLog', 'glGetProgramInfoLog'):
        body.append('\tif (length) *length = 0;\n\tif (infoLog && bufSize > 0) infoLog[0] = 0;')
    if ret == 'void':
        pass
    elif fn in ('glCreateShader', 'glCreateProgram'):
        body.append('\treturn stub_new_id();')
    elif fn == 'glGetString':
        body.append('\treturn stub_get_string(name);')
    elif fn == 'glGetStringi':
        body.append('\treturn NULL;')
    elif fn == 'glGetError':
        body.append('\treturn GL_NO_ERROR;')
    elif fn == 'glCheckFramebufferStatus':
        body.append('\treturn GL_FRAMEBUFFER_COMPLETE;')
    elif fn == 'glGetUniformLocation':
        body.append('\treturn (GLint)stub_new_id();')
    elif fn == 'glFenceSync':
        body.append('\treturn stub_new_sync();')
    elif fn == 'glClientWaitSync':
        body.append('\treturn GL_ALREADY_SIGNALED;')
    elif fn == 'glMapBufferRange':
        body.append('\treturn stub_map(length);')
    elif ret.endswith('*'):
        body.append('\treturn NULL;')
    else:
        body.append('\treturn (%s)0;' % ret)
    params = ', '.join('%s %s' % (t, n) for t, n in al) or 'void'
    lines.append('static %s APIENTRY s_%s(%s)\n{\n%s\n}' % (ret, fn, params, '\n'.join(body)))
    lines.append('%s %s = s_%s;' % (pfn, g, fn))
    lines.append('')
for f in flags:
    lines.append('int %s;' % f)
open(out, 'w').write('\n'.join(lines) + '\n')
