/*  PCSX2 - PS2 Emulator for PCs
 *
 *  H.262 (MPEG-2 Part 2) DCT coefficient VLC code tables, Tables B-14
 *  and B-15, written as the standard states them: one row per code,
 *  giving the code bits, the code length, and the (run, level) pair the
 *  code denotes.  run 64 is the end-of-block symbol and run 65 the
 *  escape, following this decoder's long-standing convention.
 *
 *  DCT_CODES_NEXT  Table B-14, coefficients after the first
 *  DCT_CODES_FIRST Table B-14 with the first (DC) coefficient variant,
 *                  where the shortest code denotes (0,1) rather than
 *                  end-of-block
 *  DCT_CODES_INTRA Table B-15, the intra-macroblock table selected by
 *                  IPU_CTRL.IVF
 *
 *  ipu_tables.c expands these into the decoder's flat lookup at the
 *  IPU's reset.  Expressed this way the tables carry no layout from
 *  any particular decoder implementation - they are the standard's own
 *  code assignments, which is what the hardware implements.
 */

