#!/bin/sh
# Writes ubershader_dynamic.inc: ubershader.comp built with DYNAMIC_VARIANT
# (its formats and variant flags read from the push constants), the way
# slangmosh builds the rest (glslc -O for Vulkan 1.1). tests/pgsdynamic
# runs this and fails when the file in the tree differs.
# Usage: ubershader_dynamic.sh [out]   (default: beside this script)
set -e
DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
OUT=${1:-$DIR/ubershader_dynamic.inc}
SPV=$(mktemp)
trap 'rm -f "$SPV"' EXIT
${GLSLC:-glslc} -fshader-stage=compute --target-env=vulkan1.1 -O -DDYNAMIC_VARIANT=1 \
	-I"$DIR" "$DIR/ubershader.comp" -o "$SPV"
{
	echo "/* Generated by ubershader_dynamic.sh from ubershader.comp: do not edit."
	echo " * glslc: $(${GLSLC:-glslc} --version | head -n 1) */"
	echo "static const uint32_t pgs_ubershader_dynamic[] ="
	echo "{"
	od -An -v -tx4 "$SPV" | awk '{ s = "\t"; for (i = 1; i <= NF; i++) s = s "0x" $i "u,"; print s }'
	echo "};"
} > "$OUT"
